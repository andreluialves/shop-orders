package repository

import (
	"context"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
)

// DBTX abstrai o que os repositories realmente usam do banco: executar e
// consultar. Tanto *pgxpool.Pool quanto pgx.Tx implementam esses métodos,
// então o mesmo repository funciona fora ou dentro de uma transação.
type DBTX interface {
	Exec(ctx context.Context, sql string, args ...any) (pgconn.CommandTag, error)
	Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error)
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
}
